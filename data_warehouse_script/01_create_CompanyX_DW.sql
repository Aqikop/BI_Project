/* ---------- dw.OrderLineFact : grain = one row per order line ---------- */
-- Loads shipped orders only (Status = 5), so there is no Status column (provisional option A).
IF OBJECT_ID(N'dw.OrderLineFact', N'U') IS NULL
CREATE TABLE dw.OrderLineFact
(
    SalesOrderID       int            NOT NULL,   -- degenerate dimension
    SalesOrderDetailID int            NOT NULL,
    ProductKey         int            NOT NULL,
    CustomerKey        int            NOT NULL,
    DateKey            int            NOT NULL,
    OrderQty           smallint       NULL,       -- nullable in source (order 43680)
    UnitPrice          decimal(19,4)  NULL,       -- nullable in source (order 43679); non-additive
    UnitPriceDiscount  decimal(19,4)  NOT NULL,   -- a 0-1 rate; non-additive
    LineTotal          decimal(38,6)  NOT NULL,   -- primary revenue measure, reconciles to source
    DiscountAmount     decimal(38,6)  NULL,       -- OrderQty * UnitPrice * UnitPriceDiscount
    OnlineOrderFlag    bit            NOT NULL,
    ModifiedDate       datetime       NOT NULL,   -- ETL watermark only
    CONSTRAINT PK_OrderLineFact PRIMARY KEY CLUSTERED (SalesOrderID, SalesOrderDetailID),
    CONSTRAINT FK_OrderLineFact_Product  FOREIGN KEY (ProductKey)  REFERENCES dw.ProductDim  (ProductKey),
    CONSTRAINT FK_OrderLineFact_Customer FOREIGN KEY (CustomerKey) REFERENCES dw.CustomerDim (CustomerKey),
    CONSTRAINT FK_OrderLineFact_Date     FOREIGN KEY (DateKey)     REFERENCES dw.DateDim     (DateKey)
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_OrderLineFact_ProductKey' AND object_id = OBJECT_ID(N'dw.OrderLineFact'))
    CREATE NONCLUSTERED INDEX IX_OrderLineFact_ProductKey  ON dw.OrderLineFact (ProductKey);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_OrderLineFact_CustomerKey' AND object_id = OBJECT_ID(N'dw.OrderLineFact'))
    CREATE NONCLUSTERED INDEX IX_OrderLineFact_CustomerKey ON dw.OrderLineFact (CustomerKey);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_OrderLineFact_DateKey' AND object_id = OBJECT_ID(N'dw.OrderLineFact'))
    CREATE NONCLUSTERED INDEX IX_OrderLineFact_DateKey     ON dw.OrderLineFact (DateKey);
GO

/* ---------- dw.AssociationRulesFact : grain = one row per discovered rule ---------- */
-- Separate mart, filled by the mining step. Logical link to ProductDim via ProductModelID
-- (not an enforced FK: ProductModelID repeats across SKUs and versions in ProductDim).
IF OBJECT_ID(N'dw.AssociationRulesFact', N'U') IS NULL
CREATE TABLE dw.AssociationRulesFact
(
    RuleKey              int IDENTITY(1,1) NOT NULL,
    AntecedentModelID    int           NOT NULL,   -- the "if" side
    ConsequentModelID    int           NOT NULL,   -- the "then" side
    AntecedentModelName  nvarchar(50)  NOT NULL,
    ConsequentModelName  nvarchar(50)  NOT NULL,
    Support              decimal(10,6) NOT NULL,
    Confidence           decimal(10,6) NOT NULL,
    Lift                 decimal(10,6) NOT NULL,
    AntecedentSupport    decimal(10,6) NOT NULL,   -- share of mined orders containing the item
    ConsequentSupport    decimal(10,6) NOT NULL,
    CoOccurrenceCount    int           NOT NULL,
    RuleClassification   varchar(20)   NOT NULL,   -- Bundle / Hidden gem / Chance / Substitute / Weak
    Channel              varchar(10)   NOT NULL,   -- Individual (main run) / Reseller (comparison run)
    GeneratedDate        datetime      NOT NULL CONSTRAINT DF_AssocRules_Generated DEFAULT (SYSDATETIME()),
    CONSTRAINT PK_AssociationRulesFact PRIMARY KEY CLUSTERED (RuleKey),
    CONSTRAINT CK_AssocRules_Class   CHECK (RuleClassification IN ('Bundle', 'Hidden gem', 'Chance', 'Substitute', 'Weak')),
    CONSTRAINT CK_AssocRules_Channel CHECK (Channel IN ('Individual', 'Reseller'))
);
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_AssocRules_Channel_Lift' AND object_id = OBJECT_ID(N'dw.AssociationRulesFact'))
    CREATE NONCLUSTERED INDEX IX_AssocRules_Channel_Lift
        ON dw.AssociationRulesFact (Channel, Lift DESC) INCLUDE (AntecedentModelID, ConsequentModelID);
GO

/* =====================================================================
   ETL CONTROL TABLES
   ===================================================================== */

/* One watermark row per loaded table; the incremental load reads LastWatermark,
   loads rows with ModifiedDate > LastWatermark, then advances it. */
IF OBJECT_ID(N'etl.Watermark', N'U') IS NULL
CREATE TABLE etl.Watermark
(
    TableName     sysname      NOT NULL,
    LastWatermark datetime     NOT NULL,
    LastRunAt     datetime     NULL,
    RowsLoaded    int          NULL,
    CONSTRAINT PK_Watermark PRIMARY KEY CLUSTERED (TableName)
);
GO

IF OBJECT_ID(N'etl.RunLog', N'U') IS NULL
CREATE TABLE etl.RunLog
(
    RunID        int IDENTITY(1,1) NOT NULL,
    PackageName  nvarchar(128) NOT NULL,
    StartedAt    datetime      NOT NULL CONSTRAINT DF_RunLog_Started DEFAULT (SYSDATETIME()),
    FinishedAt   datetime      NULL,
    [Status]     varchar(20)   NOT NULL CONSTRAINT DF_RunLog_Status DEFAULT ('Running'),  -- Running / Succeeded / Failed
    RowsRead     int           NULL,
    RowsInserted int           NULL,
    RowsUpdated  int           NULL,
    Message      nvarchar(1000) NULL,
    CONSTRAINT PK_RunLog PRIMARY KEY CLUSTERED (RunID)
);
GO

-- seed one watermark row per loaded table (1900-01-01 = nothing loaded yet)
INSERT INTO etl.Watermark (TableName, LastWatermark)
SELECT v.TableName, '1900-01-01'
FROM (VALUES (N'dw.ProductDim'), (N'dw.CustomerDim'), (N'dw.OrderLineFact')) AS v(TableName)
WHERE NOT EXISTS (SELECT 1 FROM etl.Watermark w WHERE w.TableName = v.TableName);
GO

/* =====================================================================
   DateDim population (static, generated)
   Range = min to max OrderDate in the source header (2011-05-31 to 2014-06-30)
   ===================================================================== */
IF NOT EXISTS (SELECT 1 FROM dw.DateDim)
BEGIN
    DECLARE @start date, @end date;
    SELECT @start = MIN(CAST(OrderDate AS date)),
           @end   = MAX(CAST(OrderDate AS date))
    FROM CompanyX.Sales.SalesOrderHeader;

    ;WITH d AS
    (
        SELECT @start AS dt
        UNION ALL
        SELECT DATEADD(DAY, 1, dt) FROM d WHERE dt < @end
    )
    INSERT INTO dw.DateDim
        (DateKey, FullDate, DayOfMonth, isWeekend, WeekOfYear, MonthNumber, QuarterNumber, SemesterNumber, [Year])
    SELECT
        CONVERT(int, CONVERT(char(8), dt, 112)),
        dt,
        DAY(dt),
        CASE WHEN DATEDIFF(DAY, '19000101', dt) % 7 IN (5, 6) THEN 1 ELSE 0 END,  -- 1900-01-01 was a Monday
        DATEPART(ISO_WEEK, dt),
        MONTH(dt),
        DATEPART(QUARTER, dt),
        CASE WHEN MONTH(dt) <= 6 THEN 1 ELSE 2 END,
        YEAR(dt)
    FROM d
    OPTION (MAXRECURSION 0);   -- default limit is 100 levels; the range is ~1,100 days
END
GO

