/* ---------- dw.DateDim : static (Type 0), generated by script ---------- */
IF OBJECT_ID(N'dw.DateDim', N'U') IS NULL
CREATE TABLE dw.DateDim
(
    DateKey        int      NOT NULL,   -- YYYYMMDD
    FullDate       date     NOT NULL,
    DayOfMonth     tinyint  NOT NULL,   -- 1-31
    isWeekend      bit      NOT NULL,   -- Saturday or Sunday
    WeekOfYear     tinyint  NOT NULL,   -- ISO week
    MonthNumber    tinyint  NOT NULL,   -- 1-12
    QuarterNumber  tinyint  NOT NULL,   -- 1-4
    SemesterNumber tinyint  NOT NULL,   -- 1 = Jan-Jun, 2 = Jul-Dec
    [Year]         smallint NOT NULL,
    CONSTRAINT PK_DateDim PRIMARY KEY CLUSTERED (DateKey),
    CONSTRAINT UQ_DateDim_FullDate UNIQUE (FullDate)
);
GO

/* ---------- dw.ProductDim : SCD Type 2 on ListPrice / StandardCost ---------- */
IF OBJECT_ID(N'dw.ProductDim', N'U') IS NULL
CREATE TABLE dw.ProductDim
(
    ProductKey      int IDENTITY(1,1) NOT NULL,   -- surrogate key, one per version
    ProductID       int           NOT NULL,       -- business key, repeats across versions
    [Name]          nvarchar(50)  NOT NULL,
    ProductNumber   nvarchar(25)  NOT NULL,
    Color           nvarchar(15)  NULL,
    ListPrice       decimal(19,4) NOT NULL,       -- SCD2-tracked
    StandardCost    decimal(19,4) NOT NULL,       -- SCD2-tracked
    EffectiveFrom   date          NOT NULL,
    EffectiveTo     date          NULL,           -- NULL = open-ended (current)
    IsCurrent       bit           NOT NULL,
    ProductModelID  int           NOT NULL,       -- mining grain
    ModelName       nvarchar(50)  NOT NULL,
    SubcategoryName nvarchar(50)  NOT NULL,
    CategoryName    nvarchar(50)  NOT NULL,
    SellEndDate     date          NULL,           -- NULL = still sold
    CONSTRAINT PK_ProductDim PRIMARY KEY CLUSTERED (ProductKey),
    CONSTRAINT UQ_ProductDim_Version UNIQUE (ProductID, EffectiveFrom),
    CONSTRAINT CK_ProductDim_Range CHECK (EffectiveTo IS NULL OR EffectiveTo >= EffectiveFrom)
);
GO
-- at most one current version per product
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'UX_ProductDim_Current' AND object_id = OBJECT_ID(N'dw.ProductDim'))
    CREATE UNIQUE NONCLUSTERED INDEX UX_ProductDim_Current
        ON dw.ProductDim (ProductID) WHERE IsCurrent = 1;
-- speeds up the fact-load lookup (product + order date -> version)
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_ProductDim_Lookup' AND object_id = OBJECT_ID(N'dw.ProductDim'))
    CREATE NONCLUSTERED INDEX IX_ProductDim_Lookup
        ON dw.ProductDim (ProductID, EffectiveFrom, EffectiveTo) INCLUDE (ProductKey);
-- model-level access for mining and dashboard
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_ProductDim_Model' AND object_id = OBJECT_ID(N'dw.ProductDim'))
    CREATE NONCLUSTERED INDEX IX_ProductDim_Model
        ON dw.ProductDim (ProductModelID) INCLUDE (ModelName);
GO

/* ---------- dw.CustomerDim : SCD Type 1 (overwrite) ---------- */
IF OBJECT_ID(N'dw.CustomerDim', N'U') IS NULL
CREATE TABLE dw.CustomerDim
(
    CustomerKey       int IDENTITY(1,1) NOT NULL,
    CustomerID        int           NOT NULL,     -- business key
    CustomerType      varchar(10)   NOT NULL,     -- Individual / Reseller (StoreID IS NOT NULL => Reseller)
    StoreID           int           NULL,         -- NULL for individuals
    StoreName         nvarchar(50)  NOT NULL,     -- 'N/A' for individuals
    TerritoryID       int           NOT NULL,
    TerritoryName     nvarchar(50)  NOT NULL,
    CountryRegionCode nvarchar(3)   NOT NULL,
    TerritoryGroup    nvarchar(50)  NOT NULL,     -- source column is [Group] (reserved word)
    InsertedDate      datetime      NOT NULL CONSTRAINT DF_CustomerDim_Inserted DEFAULT (SYSDATETIME()),
    UpdatedDate       datetime      NOT NULL CONSTRAINT DF_CustomerDim_Updated  DEFAULT (SYSDATETIME()),
    CONSTRAINT PK_CustomerDim PRIMARY KEY CLUSTERED (CustomerKey),
    CONSTRAINT UQ_CustomerDim_CustomerID UNIQUE (CustomerID),
    CONSTRAINT CK_CustomerDim_Type CHECK (CustomerType IN ('Individual', 'Reseller'))
);
GO

/* =====================================================================
   FACT TABLES
